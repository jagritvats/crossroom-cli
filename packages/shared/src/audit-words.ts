/** The first letter up, every dot and underscore a space: `fleet.stop_all` reads "Fleet stop all". */
export function humanizeCode(code: string): string {
  const words = code.replace(/[._-]+/g, ' ').trim();
  return words ? words[0]!.toUpperCase() + words.slice(1) : code;
}

/** What an action says, in words; a code this list does not know, humanized. */
export const auditActionWords = (action: string): string =>
  Object.hasOwn(AUDIT_ACTION_WORDS, action) ? AUDIT_ACTION_WORDS[action]! : humanizeCode(action);

/** What a target kind says, in words. */
export const auditKindWords = (kind: string): string => (Object.hasOwn(AUDIT_KIND_WORDS, kind) ? AUDIT_KIND_WORDS[kind]! : humanizeCode(kind));
